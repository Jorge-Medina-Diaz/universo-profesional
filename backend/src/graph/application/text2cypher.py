# Result types


@dataclass(frozen=True)
class CypherResult:
    cypher: str | None
    params: dict[str, Any]
    explanation: str
    rows: list[dict[str, Any]] | None = None
    error: str | None = None
    latency_ms: float = 0.0


# Validation


# AGE 1.5 lacks these functions; nodes()/shortestPath() were missing from the
# original list and would 500 at execution — reject them up front instead.
_AGE_FORBIDDEN = re.compile(
    r"\b(relationships|nodes|shortestPath|allShortestPaths|ALL|ANY|FILTER"
    r"|EXTRACT|REDUCE|FOREACH|CALL)\s*\(",
    re.IGNORECASE,
)
# query_graph is a READ path — any mutation keyword is rejected (defence in
# depth; the executor would also need write grants, but fail closed here).
_WRITE_KEYWORDS = re.compile(
    r"\b(CREATE|MERGE|SET|DELETE|REMOVE|DETACH)\b", re.IGNORECASE
)
# A raw UUID literal in generated Cypher means the model inlined an id instead
# of binding it as a param — on the personal graph that is the cross-tenant
# attack vector (e.g. `{user_id: '<victim-uuid>'}`), so reject it.
_UUID_LITERAL = re.compile(
    r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
)
# user_id must be BOUND to the server param ($user_id), not merely mentioned —
# matches both the map form `{user_id: $user_id}` and `WHERE n.user_id = $user_id`.
_USER_ID_BOUND = re.compile(r"user_id\s*[:=]\s*\$user_id")
# Capture node labels `(:Label)` / `(v:Label)` and edge types `[:T]` / `[r:T]`.
_NODE_LABEL_RE = re.compile(
    r"\(\s*(?:[A-Za-z_][A-Za-z0-9_]*)?\s*:\s*([A-Za-z_][A-Za-z0-9_]*)"
)
_EDGE_TYPE_RE = re.compile(
    r"\[\s*(?:[A-Za-z_][A-Za-z0-9_]*)?\s*:\s*([A-Za-z_][A-Za-z0-9_]*)"
)
# Personal-graph tenant scoping: EVERY node pattern must bind user_id to the
# server param. A single global "is $user_id mentioned?" check is bypassable —
# `MATCH (a:Skill {user_id:$user_id}) MATCH (b:Experience) RETURN b` scopes only
# `a` yet reads every tenant's Experience nodes (RLS does not cover AGE tables).
# Node patterns are parens NOT preceded by an identifier char (those are
# function calls like count(...)); a node is scoped if it carries
# `user_id: $user_id` in its own map OR its variable is constrained by a
# `WHERE <var>.user_id = $user_id` clause.
_NODE_PATTERN_RE = re.compile(r"(?<![A-Za-z0-9_])\(([^()]*)\)")
_NODE_VAR_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)")
_INLINE_USER_SCOPE = re.compile(r"user_id\s*:\s*\$user_id")


def _personal_scope_error(query: str) -> str | None:
    """Return an error if any personal-graph node pattern is not bound to
    $user_id. Fail closed — the contract (system prompt Rule 1) requires
    scoping every personal node; an unscoped node is a cross-tenant read."""
    if not _USER_ID_BOUND.search(query):
        return "tenant scope missing: personal-graph query must bind user_id = $user_id"
    for m in _NODE_PATTERN_RE.finditer(query):
        inner = m.group(1).strip()
        if not inner:
            continue  # anonymous () waypoint — cannot be returned, no leak
        if _INLINE_USER_SCOPE.search(inner):
            continue
        var_m = _NODE_VAR_RE.match(inner)
        var = var_m.group(1) if var_m else None
        if var and re.search(rf"\b{re.escape(var)}\.user_id\s*=\s*\$user_id", query):
            continue
        return (
            "tenant scope missing: every personal-graph node must bind "
            "user_id = $user_id (unscoped node pattern)"
        )
    return None


def _validate_query(query: str, *, graph: str) -> str | None:
    """Return an error message if *query* violates AGE/security constraints.

    Layers, fail-closed: (1) AGE-unsupported syntax, (2) single-statement,
    (3) read-only, (4) ontology allowlist (no unknown labels/edge types),
    (5) tenant scope on the personal graph — the user_id property filter is the
    ONLY isolation boundary because RLS does not cover AGE label tables.
    """
    if not query.strip():
        return "empty query"
    forbidden = _AGE_FORBIDDEN.search(query)
    if forbidden:
        return f"forbidden AGE function/keyword: {forbidden.group(0)}"
    if ";" in query:
        return "multiple statements not allowed"
    write = _WRITE_KEYWORDS.search(query)
    if write:
        return f"write operations are not allowed on graph reads: {write.group(0)}"
    for m in _NODE_LABEL_RE.finditer(query):
        if m.group(1) not in graph_schema.ALL_VERTEX_LABELS:
            return f"unknown vertex label: {m.group(1)}"
    for m in _EDGE_TYPE_RE.finditer(query):
        if m.group(1) not in graph_schema.ALL_EDGE_TYPES:
            return f"unknown edge type: {m.group(1)}"
    if graph == graph_schema.GRAPH_PERSONAL:
        scope_err = _personal_scope_error(query)
        if scope_err:
            return scope_err
        if _UUID_LITERAL.search(query):
            return "literal id not allowed: bind ids via $params, never inline UUIDs"
    return None


# Engine


class Text2CypherEngine:
    """Generate and execute openCypher from natural language."""

    def __init__(self, session: AsyncSession, user_id: UUID) -> None:
        self._session = session
        self._user_id = user_id
        self._settings = get_settings()

    async def generate(
        self, question: str, graph: str = graph_schema.GRAPH_PERSONAL
    ) -> CypherResult:
        """Generate Cypher from *question*.  Does NOT execute."""
        import time

        start = time.perf_counter()

        # Build the prompt
        messages = [
            {"role": "system", "content": _SYSTEM_PROMPT},
            {"role": "user", "content": question},
        ]

        # Call LLM
        try:
            llm_response = await self._call_llm(messages)
        except Exception as exc:
            logger.warning("text2cypher_llm_failed", error=str(exc))
            return CypherResult(
                cypher=None, params={}, explanation=f"LLM error: {exc}", latency_ms=0.0
            )

        # Parse JSON
        try:
            parsed = json.loads(llm_response)
            cypher_str = parsed.get("cypher")
            params = parsed.get("params", {})
            explanation = parsed.get("explanation", "")
        except json.JSONDecodeError:
            # Fallback: try to extract JSON from markdown fence
            fence_match = re.search(r"```json\s*(.*?)\s*```", llm_response, re.DOTALL)
            if fence_match:
                try:
                    parsed = json.loads(fence_match.group(1))
                    cypher_str = parsed.get("cypher")
                    params = parsed.get("params", {})
                    explanation = parsed.get("explanation", "")
                except json.JSONDecodeError:
                    return CypherResult(
                        cypher=None,
                        params={},
                        explanation="LLM returned invalid JSON",
                        latency_ms=(time.perf_counter() - start) * 1000,
                    )
            else:
                return CypherResult(
                    cypher=None,
                    params={},
                    explanation="LLM returned invalid JSON",
                    latency_ms=(time.perf_counter() - start) * 1000,
                )

        if not cypher_str:
            return CypherResult(
                cypher=None,
                params=params,
                explanation=explanation,
                latency_ms=(time.perf_counter() - start) * 1000,
            )

        # Force the server-bound tenant id — NEVER trust the LLM's user_id.
        # Dropping any model-supplied value closes the param-override vector;
        # the validator additionally rejects inline UUID literals.
        params = dict(params)
        params.pop("user_id", None)
        params["user_id"] = str(self._user_id)

        # Validate (AGE syntax + read-only + ontology allowlist + tenant scope)
        validation_err = _validate_query(cypher_str, graph=graph)
        if validation_err:
            return CypherResult(
                cypher=cypher_str,
                params=params,
                explanation=f"Generated but invalid: {validation_err}",
                error=validation_err,
                latency_ms=(time.perf_counter() - start) * 1000,
            )

        return CypherResult(
            cypher=cypher_str,
            params=params,
            explanation=explanation,
            latency_ms=(time.perf_counter() - start) * 1000,
        )

    async def execute(
        self, result: CypherResult, graph: str = graph_schema.GRAPH_PERSONAL
    ) -> CypherResult:
        """Execute a generated CypherResult against AGE."""
        if result.cypher is None or result.error:
            return result

        import time

        start = time.perf_counter()
        try:
            # The system prompt encourages multi-column projections
            # (`RETURN n.name, n.confidence`), but AGE requires the AS(...) column
            # arity to match. Derive it from the RETURN clause instead of
            # hardcoding a single column (which 'number of columns' errored).
            n_cols = _count_return_columns(result.cypher)
            col_names = ["result"] if n_cols <= 1 else [f"col{i}" for i in range(n_cols)]
            column_defs = ", ".join(f"{c} agtype" for c in col_names)

            rows = await cypher(
                self._session,
                graph,
                result.cypher,
                params=result.params,
                column_defs=column_defs,
            )
            from src.graph.application.ports.age import parse_agtype

            def _p(v: Any) -> Any:
                return parse_agtype(v) if v is not None else None

            parsed_rows = []
            for r in rows:
                if n_cols <= 1:
                    parsed_rows.append(_p(r.get("result")))
                else:
                    parsed_rows.append({c: _p(r.get(c)) for c in col_names})

            latency = result.latency_ms + (time.perf_counter() - start) * 1000
            return CypherResult(
                cypher=result.cypher,
                params=result.params,
                explanation=result.explanation,
                rows=parsed_rows,
                latency_ms=latency,
            )
        except Exception as exc:
            logger.warning("text2cypher_execution_failed", error=str(exc), cypher=result.cypher)
            latency = result.latency_ms + (time.perf_counter() - start) * 1000
            return CypherResult(
                cypher=result.cypher,
                params=result.params,
                explanation=result.explanation,
                error=str(exc),
                latency_ms=latency,
            )

    async def ask(self, question: str, graph: str = graph_schema.GRAPH_PERSONAL) -> CypherResult:
        """Generate + execute in one call."""
        gen = await self.generate(question, graph)
        return await self.execute(gen, graph)

    async def _call_llm(self, messages: list[dict[str, str]]) -> str:
        """Route to the configured LLM provider."""
        provider = self._settings.agents_provider_resolved
        if provider == "anthropic":
            return await self._call_anthropic(messages)
        if provider == "openai":
            return await self._call_openai(messages)
        # Mock fallback — deterministic response for tests
        return json.dumps(
            {
                "cypher": "MATCH (n {user_id: $user_id}) RETURN count(n) AS total",
                "params": {"user_id": str(self._user_id)},
                "explanation": "Mock response: counting user nodes",
            }
        )

    async def _call_anthropic(self, messages: list[dict[str, str]]) -> str:
        from anthropic import AsyncAnthropic

        client = AsyncAnthropic(api_key=self._settings.anthropic_api_key)
        system = messages[0]["content"]
        user_msgs = [m for m in messages[1:] if m["role"] == "user"]
        response = await client.messages.create(
            model=self._settings.agents_specialist_model or "claude-haiku-4-5-20251001",
            max_tokens=1024,
            system=system,
            messages=[{"role": "user", "content": m["content"]} for m in user_msgs],
        )
        return anthropic_text(response.content)

    async def _call_openai(self, messages: list[dict[str, str]]) -> str:
        from openai import AsyncOpenAI
        from openai.types.chat import ChatCompletionMessageParam

        client = AsyncOpenAI(api_key=self._settings.openai_api_key)
        response = await client.chat.completions.create(
            model="gpt-4o-mini",
            messages=cast(list[ChatCompletionMessageParam], messages),
            max_tokens=1024,
            temperature=0.1,
        )
        return str(response.choices[0].message.content)
