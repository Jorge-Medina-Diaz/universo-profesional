"""Text2Cypher — Natural language → openCypher for Apache AGE.

Sprint R introduces structured graph queries generated by LLMs so the agent
can reason about trajectories, implicit skills, and ESCO-based gaps without
relying solely on vector similarity.

Architecture:
  1. Schema descriptor — auto-built from graph/domain/schema.py
  2. LLM prompt — system prompt with schema + AGE 1.5 constraints
  3. Generation — single-shot LLM call (fast, cheap model)
  4. Validation — regex-based sanity checks + AGE-specific restrictions
  5. Execution — run against AGE with timeout, return structured results

Gupta & Tadayon (2026) report >90% accuracy for text-to-Cypher with a
well-schematised prompt; our domain is narrower (career graph only) so we
target 95%+ for common queries.
"""
